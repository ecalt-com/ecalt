"""Turn a Supabase schema-only dump into tests/db/schema_baseline.sql.

    python tests/db/prepare_schema.py ../supbase/schema.sql

Strips what plain Postgres can't load (Supabase-only extensions, the realtime
publication). The input must be a SCHEMA-ONLY dump (`pg_dump -s` / `supabase db
dump`). The script refuses input containing INSERT or COPY statements, so a
data dump such as supbase/data.sql can never end up in the repo.

After regenerating, set BASELINE_MIGRATION in tests/schools/harness.py to the
last migration number the dump already contains.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "schema_baseline.sql"

_DROP_PATTERNS = [
    re.compile(r'^CREATE EXTENSION IF NOT EXISTS "(hypopg|index_advisor|pg_stat_statements|supabase_vault)"'),
    re.compile(r'^ALTER PUBLICATION "supabase_realtime"'),
]
_DATA_PATTERN = re.compile(r"^(INSERT INTO|COPY )", re.MULTILINE)

HEADER = """\
-- Schema-only baseline for the local DB integration tests (never production).
-- Generated by tests/db/prepare_schema.py from a Supabase schema dump; contains
-- no data. Migrations after BASELINE_MIGRATION (tests/schools/harness.py) are
-- applied on top by the harness.

"""


def main(src: str) -> None:
    text = Path(src).read_text(encoding="utf-8")
    if _DATA_PATTERN.search(text):
        sys.exit(f"{src} contains INSERT/COPY statements — only schema-only dumps are allowed.")
    kept = [line for line in text.splitlines() if not any(p.match(line) for p in _DROP_PATTERNS)]
    OUT.write_text(HEADER + "\n".join(kept) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(kept)} lines)")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
